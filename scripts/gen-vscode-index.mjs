// Regenerate src/pokemon/vscode-index.ts from a local clone of
// https://github.com/jakobhoeg/vscode-pokemon (its code/data is CC0).
// Only names, numbers and which sprite files exist are copied, never images.
//
//   git clone --depth 1 https://github.com/jakobhoeg/vscode-pokemon.git /tmp/vscode-pokemon
//   node scripts/gen-vscode-index.mjs /tmp/vscode-pokemon
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2];
if (!root) throw new Error("usage: node scripts/gen-vscode-index.mjs <vscode-pokemon clone>");
const commit = process.argv[3] ?? "main";
const source = readFileSync(join(root, "src/common/pokemon-data.ts"), "utf8");
const entry = /^  ([a-z0-9_]+): \{\n([\s\S]*?)\n  \},/gm;

const rows = [];
for (const [, key, body] of source.matchAll(entry)) {
  const id = Number(/id: (\d+)/.exec(body)?.[1]);
  const name = /name: '((?:[^'\\]|\\.)*)'/.exec(body)?.[1]?.replace(/\\'/g, "'");
  const gen = Number(/PokemonGeneration\.Gen(\d)/.exec(body)?.[1]);
  if (!id || !name || !gen) continue;
  const dir = join(root, "media", `gen${gen}`, key);
  const has = (file) => existsSync(join(dir, file));
  if (!has("default_idle_8fps.gif") || !has("default_walk_8fps.gif")) continue;
  const flags = (has("shiny_idle_8fps.gif") && has("shiny_walk_8fps.gif") ? 1 : 0) | (has("default_walk_left_8fps.gif") ? 2 : 0);
  rows.push(`  [${JSON.stringify(key)}, ${id}, ${JSON.stringify(name)}, ${gen}, ${flags}],`);
}

writeFileSync(
  new URL("../src/pokemon/vscode-index.ts", import.meta.url),
  `// Generated by scripts/gen-vscode-index.mjs from jakobhoeg/vscode-pokemon. Do not edit.
// [folder key, National Dex number, display name, generation, flags (1 = shiny, 2 = walk-left sprite)]
export const VSCODE_POKEMON_REF = ${JSON.stringify(commit)};
export const VSCODE_POKEMON: ReadonlyArray<readonly [string, number, string, number, number]> = [
${rows.join("\n")}
];
`,
);
console.log(`wrote ${rows.length} Pokémon`);
